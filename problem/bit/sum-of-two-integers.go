package bit

func getSum(a int, b int) int {
	for b != 0 {
		tmp := (a & b) << 1 // 1. หาตัวทด (Carry) เก็บไว้ใน tmp (1 & 1 = 1 นอกนั้น 0)
		a = a ^ b           // 2. หาผลบวก (ยังไม่รวมตัวทด) แล้วเก็บไว้ที่ a (XOR เหมือนกันได้ 0 ต่างกันได้ 1)
		b = tmp             // 3. เอาตัวทดมาใส่ใน b เพื่อเตรียมเอาไปบวกกับ a ในรอบถัดไป
	}
	return a // 4. ลูปจะหยุดเมื่อไม่มีตัวทดเหลือแล้ว (b == 0) ผลลัพธ์สุดท้ายจะอยู่ที่ a
}
